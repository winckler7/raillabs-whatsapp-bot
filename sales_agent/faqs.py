# FAQs tecnicas sobre el servicio de agentes de WhatsApp.
#
# NOTA: Estas respuestas son un borrador razonable basado en el contexto que
# diste (Meta Business Suite, WhatsApp Business, CRM, sitio web). Revisa y
# ajusta los datos concretos (tiempos, integraciones exactas, precios) antes
# de usarlas en producción — aqui solo modelo el formato y el tono.

FAQS = """
PREGUNTAS_FRECUENTES:

P: ¿Qué es Meta Business Suite y por qué lo necesito?
R: Es la plataforma de Meta donde administras tu página de Facebook, Instagram
y WhatsApp Business en un solo lugar. La necesitamos porque ahí es donde se
conecta el agente de IA para poder leer y responder tus mensajes.

P: ¿Qué diferencia hay entre WhatsApp normal y WhatsApp Business?
R: WhatsApp Business es la versión para empresas de Meta, con catálogo,
respuestas automáticas y, sobre todo, la API que permite conectar
herramientas externas como nuestro agente de IA. WhatsApp normal no lo permite.

P: ¿El agente puede acceder a mi CRM?
R: Sí, contamos con integraciones para conectar el agente a CRMs populares
(por ejemplo HubSpot, Pipedrive o uno a la medida) para que registre leads y
actualice el estado de cada conversación automáticamente.

P: ¿El agente puede tomar información de mi página web?
R: Sí, podemos entrenarlo con el contenido de tu sitio (servicios, precios,
preguntas frecuentes) para que responda con información específica de tu
negocio y no solo de forma genérica.

P: ¿Cuánto tarda la implementación?
R: Depende de la cantidad de integraciones que se necesiten, pero un agente
básico conectado a WhatsApp Business suele estar listo en pocos días hábiles.

P: ¿El agente reemplaza por completo a una persona?
R: Automatiza la primera parte del proceso: atender, calificar y agendar.
Las llamadas y el cierre de venta los sigue haciendo tu equipo humano — el
agente les ahorra el tiempo de contestar uno por uno.

P: ¿Funciona las 24 horas?
R: Sí, el agente está disponible todo el tiempo, incluyendo fines de semana y
fuera de horario laboral, para que ningún interesado se quede sin respuesta.

P: ¿Es seguro? ¿Qué pasa con los datos de mis clientes?
R: La conversación se maneja a través de la infraestructura oficial de Meta
para WhatsApp Business, y los datos que el agente recopila (nombre, interés,
disponibilidad) solo se usan para el proceso de venta y agendado.

P: ¿El precio es único pago o mensualidad?
R: Depende del alcance de tu proyecto (tecnologías que agregues, volumen de
conversaciones, si necesitas mantenimiento mensual) -- Jorge te da el
precio exacto en la llamada, una vez que conoce mejor tu caso.

P: ¿Puedo usar el número de WhatsApp que ya tengo?
R: No -- la API de WhatsApp Business necesita un número que no esté
registrado en WhatsApp (ni normal ni Business) al momento de conectarlo.
Si tu número actual ya lo usas para hablar con clientes, vas a necesitar un
número nuevo dedicado para el bot -- te ayudamos a configurarlo.

P: No tengo página de Facebook ni WhatsApp Business todavía, ¿qué hago?
R: No hay problema, podemos ayudarte a configurarlos desde cero antes de
instalar el agente — es un paso previo que también acompañamos.

P: ¿Puede manejar varias conversaciones al mismo tiempo?
R: Sí, esa es una de las ventajas principales: puede atender a todos tus
interesados en simultáneo, sin filas de espera.
"""
